function prepareSource(name, source, expectedCronStatements) {
  const hashLiterals = source.match(/\b[0-9a-f]{64}\b/gu) || [];
  assert.equal(
    hashLiterals.length,
    expectedTokenHashOccurrences[name],
    `${name} token-hash occurrence contract changed`
  );
  assert.ok(
    hashLiterals.every((hash) => hash === productionTokenHash),
    `${name} contains an unexpected SHA-256 token literal`
  );

  let prepared = source.replaceAll(productionTokenHash, fixtureTokenHash);
  assert.equal(prepared.includes(productionTokenHash), false, `${name} retained the production token hash`);
  assert.equal(
    (prepared.match(new RegExp(fixtureTokenHash, 'gu')) || []).length,
    expectedTokenHashOccurrences[name],
    `${name} fixture token-hash replacement is incomplete`
  );

  const cronStatements = prepared.match(pgCronStatement) || [];
  assert.equal(
    cronStatements.length,
    expectedCronStatements,
    `${name} pg_cron extension contract changed`
  );
  if (expectedCronStatements > 0) {
    prepared = prepared.replace(pgCronStatement, '-- PGlite semantic gate uses the cron shim below.');
  }

  return prepared;
}

function prepareSql(name) {
  const source = sqlFiles[name];
  assert.ok(source, `Unknown SQL fixture: ${name}`);
  return prepareSource(name, source, name === 'add_history.sql' ? 1 : 0);
}

