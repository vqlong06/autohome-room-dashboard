async function runPreflightFailure() {
  console.log('Semantic gate: fail-closed preflight');
  const database = await createDatabase();
  try {
    await applyCurrentBootstrap(database);
    await seedTelemetry(database);
    const telemetry = await telemetryFingerprint(database);
    await database.exec(`
      create policy semantic_unexpected_policy
      on public.room_latest for select to anon using (true);
    `);
    await assert.rejects(
      () => database.exec(hardeningSql),
      /Unexpected LongOS policies: public\.semantic_unexpected_policy/u
    );
    await database.exec('rollback;');
    await assertTelemetryFingerprint(database, telemetry, 'unexpected-policy preflight');

    const policy = await database.query(`
      select count(*)::integer as count
      from pg_catalog.pg_policies
      where schemaname = 'public'
        and tablename = 'room_latest'
        and policyname = 'semantic_unexpected_policy'
    `);
    assert.deepEqual(policy.rows, [{ count: 1 }], 'preflight failure must leave existing state unchanged');
  } finally {
    await closeDatabase(database);
  }
}

