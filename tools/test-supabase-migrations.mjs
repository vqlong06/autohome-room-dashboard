async function telemetryFingerprint(database) {
  const result = await database.query(`
    select
      (
        select pg_catalog.md5(coalesce(
          pg_catalog.string_agg(pg_catalog.row_to_json(latest_row)::text, E'\\n' order by room_id),
          ''
        ))
        from public.room_latest latest_row
      ) as latest_hash,
      (
        select pg_catalog.count(*)::integer
        from public.room_latest
      ) as latest_count,
      (
        select pg_catalog.md5(coalesce(
          pg_catalog.string_agg(pg_catalog.row_to_json(history_row)::text, E'\\n' order by id),
          ''
        ))
        from public.room_readings history_row
      ) as history_hash,
      (
        select pg_catalog.count(*)::integer
        from public.room_readings
      ) as history_count
  `);
  assert.equal(result.rows.length, 1);
  return result.rows[0];
}

async function assertTelemetryFingerprint(database, expected, label) {
  assert.deepEqual(await telemetryFingerprint(database), expected, `${label}: telemetry changed`);
}

async function assertBehavior(database) {
  await database.exec(`
    insert into public.room_latest (
      room_id, app_version, device_online, wifi_connected, sensor_online, source
    ) values (
      'other-room', 'hidden-room', true, true, true, 'semantic-fixture'
    );
  `);

  const visible = await withRole(database, 'anon', {}, () => database.query(`
    select room_id from public.room_latest order by room_id
  `));
  assert.deepEqual(visible.rows, [{ room_id: 'main-room' }], 'anon must only read main-room');

  await withRole(database, 'anon', { 'x-device-token': 'wrong-token' }, () => database.exec(`
    update public.room_latest set app_version = 'invalid-token' where room_id = 'main-room';
  `));
  const invalidUpdate = await database.query(`
    select app_version from public.room_latest where room_id = 'main-room'
  `);
  assert.equal(
    invalidUpdate.rows[0].app_version,
    'semantic-seed',
    'wrong device token must update zero rows'
  );

  await expectDenied(
    () => withRole(database, 'anon', { 'x-device-token': 'wrong-token' }, () => database.exec(`
      insert into public.room_latest (
        room_id, app_version, device_online, wifi_connected, sensor_online, source
      ) values (
        'main-room', 'invalid-upsert', true, true, true, 'semantic-fixture'
      ) on conflict (room_id) do update
      set app_version = excluded.app_version;
    `)),
    'wrong device token must not upsert latest'
  );

  await expectDenied(
    () => withRole(database, 'anon', { 'x-device-token': fixtureToken }, () => database.exec(`
      insert into public.room_latest (
        room_id, app_version, device_online, wifi_connected, sensor_online, source
      ) values ('blocked-room', 'wrong-room', true, true, true, 'semantic-fixture');
    `)),
    'valid token must not write another room'
  );

  await withRole(database, 'anon', { 'x-device-token': fixtureToken }, () => database.exec(`
    insert into public.room_latest (
      room_id, updated_at, app_version, device_online, wifi_connected, sensor_online, source
    ) values (
      'main-room', '2000-01-01T00:00:00Z', 'semantic-valid-write',
      true, true, true, 'semantic-fixture'
    ) on conflict (room_id) do update
    set updated_at = excluded.updated_at,
        app_version = excluded.app_version,
        device_online = excluded.device_online,
        wifi_connected = excluded.wifi_connected,
        sensor_online = excluded.sensor_online,
        source = excluded.source;

    insert into public.room_readings (
      room_id, app_version, sensor_online, temperature_c, humidity, source, uptime_ms
    ) values (
      'main-room', 'semantic-valid-write', true, 25.4, 61, 'semantic-fixture', 2000
    );
  `));

  const written = await database.query(`
    select app_version,
           updated_at > pg_catalog.now() - interval '1 minute' as trigger_replaced_timestamp
    from public.room_latest where room_id = 'main-room'
  `);
  assert.deepEqual(written.rows, [{
    app_version: 'semantic-valid-write',
    trigger_replaced_timestamp: true
  }]);

  await expectDenied(
    () => withRole(database, 'anon', { 'x-device-token': fixtureToken }, () => database.exec(`
      delete from public.room_latest where room_id = 'main-room';
    `)),
    'anon must not delete latest'
  );
  await expectDenied(
    () => withRole(database, 'anon', { 'x-device-token': fixtureToken }, () => database.exec(`
      update public.room_readings set source = 'blocked-update' where room_id = 'main-room';
    `)),
    'anon must not update history'
  );
  await expectDenied(
    () => withRole(database, 'anon', { 'x-device-token': 'wrong-token' }, () => database.exec(`
      insert into public.room_readings (
        room_id, app_version, sensor_online, source
      ) values ('main-room', 'invalid-history', true, 'semantic-fixture');
    `)),
    'wrong device token must not insert history'
  );
  await expectDenied(
    () => withRole(database, 'authenticated', {}, () => database.query(`
      select room_id from public.room_latest
    `)),
    'authenticated role must not read public telemetry'
  );
  await expectDenied(
    () => withRole(database, 'anon', {}, () => database.query(`
      select longos_private.snapshot_room_reading()
    `)),
    'anon must not execute the private snapshot helper'
  );

  const rpcState = await database.query(`
    select
      pg_catalog.to_regprocedure('public.valid_room_device_token()') is null as token_removed,
      pg_catalog.to_regprocedure('public.snapshot_room_reading()') is null as snapshot_removed,
      pg_catalog.to_regprocedure('public.valid_room_dashboard_token()') is null as dashboard_removed
  `);
  assert.deepEqual(rpcState.rows, [{
    token_removed: true,
    snapshot_removed: true,
    dashboard_removed: true
  }]);

  await database.exec(`
    update public.room_readings
    set recorded_at = pg_catalog.now() - interval '1 hour';
  `);
  const beforeSnapshot = await database.query(`select count(*)::integer as count from public.room_readings`);
  await database.exec(`select longos_private.snapshot_room_reading();`);
  await database.exec(`select longos_private.snapshot_room_reading();`);
  const afterSnapshot = await database.query(`select count(*)::integer as count from public.room_readings`);
  assert.equal(
    afterSnapshot.rows[0].count,
    beforeSnapshot.rows[0].count + 1,
    'snapshot helper must add one fallback sample and suppress an immediate duplicate'
  );

  await database.exec(`
    create function public.semantic_default_acl_canary()
    returns integer language sql as $$ select 1; $$;
  `);
  const canary = await database.query(`
    select not pg_catalog.has_function_privilege(
      'anon',
      'public.semantic_default_acl_canary()',
      'EXECUTE'
    ) as execute_is_private
  `);
  assert.deepEqual(canary.rows, [{ execute_is_private: true }]);
  await database.exec(`drop function public.semantic_default_acl_canary();`);
}

async function runFreshBootstrap() {
  console.log('Semantic gate: fresh bootstrap behavior');
  const database = await createDatabase();
  try {
    await applyCurrentBootstrap(database);
    await seedTelemetry(database);
    await database.exec(`
      insert into public.room_latest (
        room_id, app_version, device_online, wifi_connected, sensor_online, source
      ) values ('other-room', 'hidden-room', true, true, true, 'semantic-fixture');
    `);

    const catalog = await database.query(`
      select
        pg_catalog.to_regprocedure('public.valid_room_device_token()') is null
          as public_token_helper_absent,
        pg_catalog.to_regprocedure('longos_private.valid_room_device_token()') is not null
          as private_token_helper_present,
        pg_catalog.to_regprocedure('longos_private.snapshot_room_reading()') is null
          as snapshot_helper_deferred,
        pg_catalog.has_table_privilege('anon', 'public.room_latest', 'SELECT,INSERT,UPDATE')
          as latest_privileges_present,
        not pg_catalog.has_table_privilege('anon', 'public.room_latest', 'DELETE')
          as latest_delete_absent,
        pg_catalog.has_table_privilege('anon', 'public.room_readings', 'SELECT,INSERT')
          as history_privileges_present,
        not pg_catalog.has_table_privilege('anon', 'public.room_readings', 'UPDATE,DELETE')
          as history_mutation_absent,
        pg_catalog.has_sequence_privilege('anon', 'public.room_readings_id_seq', 'USAGE')
          as sequence_usage_present,
        not pg_catalog.has_sequence_privilege('anon', 'public.room_readings_id_seq', 'SELECT,UPDATE')
          as sequence_extra_privileges_absent,
        not pg_catalog.has_schema_privilege('anon', 'public', 'CREATE')
          as public_create_locked,
        not pg_catalog.has_table_privilege('authenticated', 'public.room_latest', 'SELECT')
          as authenticated_read_absent
    `);
    assert.deepEqual(catalog.rows, [{
      public_token_helper_absent: true,
      private_token_helper_present: true,
      snapshot_helper_deferred: true,
      latest_privileges_present: true,
      latest_delete_absent: true,
      history_privileges_present: true,
      history_mutation_absent: true,
      sequence_usage_present: true,
      sequence_extra_privileges_absent: true,
      public_create_locked: true,
      authenticated_read_absent: true
    }]);

    const visible = await withRole(database, 'anon', {}, () => database.query(`
      select room_id from public.room_latest order by room_id
    `));
    assert.deepEqual(visible.rows, [{ room_id: 'main-room' }]);

    await withRole(database, 'anon', { 'x-device-token': 'wrong-token' }, () => database.exec(`
      update public.room_latest set app_version = 'fresh-invalid' where room_id = 'main-room';
    `));
    const invalid = await database.query(`
      select app_version from public.room_latest where room_id = 'main-room'
    `);
    assert.equal(invalid.rows[0].app_version, 'semantic-seed');

    await expectDenied(
      () => withRole(database, 'anon', { 'x-device-token': 'wrong-token' }, () => database.exec(`
        insert into public.room_readings (
          room_id, app_version, sensor_online, source
        ) values ('main-room', 'fresh-invalid', true, 'semantic-fixture');
      `)),
      'fresh bootstrap must reject an invalid history token'
    );

    await withRole(database, 'anon', { 'x-device-token': fixtureToken }, () => database.exec(`
      update public.room_latest
      set app_version = 'fresh-valid', updated_at = '2000-01-01T00:00:00Z'
      where room_id = 'main-room';
      insert into public.room_readings (
        room_id, app_version, sensor_online, source
      ) values ('main-room', 'fresh-valid', true, 'semantic-fixture');
    `));
    const valid = await database.query(`
      select
        app_version,
        updated_at > pg_catalog.now() - interval '1 minute' as trigger_replaced_timestamp
      from public.room_latest where room_id = 'main-room'
    `);
    assert.deepEqual(valid.rows, [{ app_version: 'fresh-valid', trigger_replaced_timestamp: true }]);

    const cron = await database.query(`
      select jobname, schedule, active from cron.job order by jobname
    `);
    assert.deepEqual(cron.rows, [{
      jobname: 'autohome-cleanup',
      schedule: '17 3 * * *',
      active: true
    }]);
  } finally {
    await closeDatabase(database);
  }
}

async function runHappyPath() {
  console.log('Semantic gate: legacy hardening, behavior, idempotency and rollback');
  const database = await createDatabase();
  try {
    await applyLegacyBootstrap(database);
    await database.exec(`
      grant create on schema public to public, anon, authenticated, service_role;
      grant all on table public.room_latest, public.room_readings to public, authenticated;
      grant all on sequence public.room_readings_id_seq to public, authenticated;
    `);
    await seedTelemetry(database);
    const legacyTelemetry = await telemetryFingerprint(database);
    await database.exec(hardeningSql);
    await assertVerifierPass(database, 'legacy hardening');
    await assertTelemetryFingerprint(database, legacyTelemetry, 'legacy hardening');

    const cron = await database.query(`
      select jobname, schedule, active
      from cron.job order by jobname
    `);
    assert.deepEqual(cron.rows, [{
      jobname: 'autohome-cleanup',
      schedule: '17 3 * * *',
      active: true
    }]);

    await assertBehavior(database);
    const hardenedTelemetry = await telemetryFingerprint(database);
    await database.exec(hardeningSql);
    await assertVerifierPass(database, 'idempotent hardening');
    await assertTelemetryFingerprint(database, hardenedTelemetry, 'idempotent hardening');

    await database.exec(rollbackSql);
    await assertTelemetryFingerprint(database, hardenedTelemetry, 'security rollback');
    const rollbackVerifier = await verifierResult(database);
    assert.equal(rollbackVerifier.longos_security_result, 'FAIL');
    assert.equal(rollbackVerifier.private_token_helper_definition, false);
    assert.equal(rollbackVerifier.legacy_snapshot_disabled, true);

    await withRole(database, 'anon', { 'x-device-token': fixtureToken }, () => database.exec(`
      update public.room_latest set app_version = 'semantic-rollback-write' where room_id = 'main-room';
      insert into public.room_readings (
        room_id, app_version, sensor_online, source
      ) values ('main-room', 'semantic-rollback-write', true, 'semantic-fixture');
    `));
    const rollbackWriteTelemetry = await telemetryFingerprint(database);
    await withRole(database, 'anon', { 'x-device-token': 'wrong-token' }, () => database.exec(`
      update public.room_latest set app_version = 'rollback-invalid' where room_id = 'main-room';
    `));
    const rollbackInvalid = await database.query(`
      select app_version from public.room_latest where room_id = 'main-room'
    `);
    assert.equal(
      rollbackInvalid.rows[0].app_version,
      'semantic-rollback-write',
      'rollback must keep invalid-token updates at zero rows'
    );
    await assertTelemetryFingerprint(
      database,
      rollbackWriteTelemetry,
      'rollback invalid-token rejection'
    );

    await database.exec(hardeningSql);
    await assertVerifierPass(database, 'rehardening after rollback');
    await assertTelemetryFingerprint(database, rollbackWriteTelemetry, 'rehardening after rollback');
  } finally {
    await closeDatabase(database);
  }
}

