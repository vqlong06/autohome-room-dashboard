async function verifierResult(database) {
  const result = await database.query(verifierSql);
  assert.equal(result.rows.length, 1, 'security verifier must return exactly one row');
  return result.rows[0];
}

async function assertVerifierPass(database, label) {
  const row = await verifierResult(database);
  assert.equal(row.longos_security_result, 'PASS', `${label}: verifier result must be PASS`);
  for (const field of booleanVerifierFields) {
    assert.equal(row[field], true, `${label}: ${field} must be true`);
  }
  assert.deepEqual(
    Object.keys(row).sort(),
    ['longos_security_result', ...booleanVerifierFields].sort(),
    `${label}: verifier column contract changed`
  );
  return row;
}

async function assertVerifierFailure(database, field, label) {
  const row = await verifierResult(database);
  assert.equal(row.longos_security_result, 'FAIL', `${label}: verifier must fail`);
  assert.equal(row[field], false, `${label}: ${field} must identify the mutation`);
}

async function withRole(database, role, headers, operation) {
  assert.ok(['anon', 'authenticated'].includes(role), `Unsupported semantic role: ${role}`);
  await database.exec(`set role ${role};`);
  try {
    await database.query(
      "select pg_catalog.set_config('request.headers', $1, false)",
      [JSON.stringify(headers)]
    );
    return await operation();
  } finally {
    await database.exec('reset role;');
    await database.query("select pg_catalog.set_config('request.headers', '', false)");
  }
}

async function expectDenied(operation, label) {
  await assert.rejects(operation, /permission denied|row-level security policy|violates row-level security/iu, label);
}

