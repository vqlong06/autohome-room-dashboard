const bootstrapSql = `
  create role anon nologin;
  create role authenticated nologin;
  create role service_role nologin bypassrls;

  grant usage on schema public to anon, authenticated, service_role;

  create schema cron;
  create table cron.job (
    jobid bigint generated by default as identity primary key,
    jobname text not null unique,
    schedule text not null,
    command text not null,
    database text not null default current_database(),
    active boolean not null default true
  );

  create function cron.unschedule(target_job_id bigint)
  returns boolean
  language plpgsql
  security invoker
  set search_path = ''
  as $$
  declare
    deleted_count bigint;
  begin
    delete from cron.job where jobid = target_job_id;
    get diagnostics deleted_count = row_count;
    return deleted_count > 0;
  end;
  $$;

  create function cron.unschedule(target_job_name text)
  returns boolean
  language plpgsql
  security invoker
  set search_path = ''
  as $$
  declare
    deleted_count bigint;
  begin
    delete from cron.job where jobname = target_job_name;
    get diagnostics deleted_count = row_count;
    return deleted_count > 0;
  end;
  $$;

  create function cron.schedule(job_name text, cron_schedule text, cron_command text)
  returns bigint
  language plpgsql
  security invoker
  set search_path = ''
  as $$
  declare
    scheduled_job_id bigint;
  begin
    insert into cron.job (jobname, schedule, command, database, active)
    values (job_name, cron_schedule, cron_command, pg_catalog.current_database(), true)
    on conflict (jobname) do update
    set schedule = excluded.schedule,
        command = excluded.command,
        database = excluded.database,
        active = true
    returning jobid into scheduled_job_id;
    return scheduled_job_id;
  end;
  $$;
`;

async function createDatabase() {
  const database = await PGlite.create({ extensions: { pgcrypto } });
  await database.exec(bootstrapSql);
  return database;
}

async function closeDatabase(database) {
  await database.close();
}

async function applyCurrentBootstrap(database) {
  await database.exec(roomLatestSql);
  await database.exec(addHistorySql);
}

